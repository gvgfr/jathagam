/**
 * @param {Record<string, number>} signs sign index (0-11) of sun..saturn and 'lagnam'
 * @returns {{bav: Record<string, number[]>, sav: number[]}} bindus per sign (index 0 = Mesham)
 */
export function ashtakavarga(signs) {
  const bav = {};
  const sav = Array(12).fill(0);
  for (const [planet, refs] of Object.entries(TABLE)) {
    const row = Array(12).fill(0);
    for (const r of REF) for (const h of refs[r]) row[(signs[r] + h - 1) % 12] += 1;
    bav[planet] = row;
    row.forEach((v, i) => (sav[i] += v));
  }
  return { bav, sav };
}
