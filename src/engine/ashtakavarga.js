// Ashtakavarga (BPHS ch. 66-72): each of the seven planets gets a "bindu"
// (benefic point) in a sign when it is placed in certain houses counted from
// eight reference points (the seven planets and the lagnam). Totals per planet
// are fixed (Sun 48, Moon 49, Mars 39, Mercury 54, Jupiter 56, Venus 52,
// Saturn 39; Sarvashtakavarga 337). Used to judge transits: a planet moving
// through a sign with 4+ of its own bindus, or a sign with 28+ total, is
// traditionally favourable for you.
const REF = ['sun', 'moon', 'mars', 'mercury', 'jupiter', 'venus', 'saturn', 'lagnam'];

